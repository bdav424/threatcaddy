export function getMascot(id: AmbientAssistantCharacter | undefined): MascotDefinition {
  return AMBIENT_MASCOTS.find((m) => m.id === id) ?? AMBIENT_MASCOTS[0];
}

/** Fills any missing slot in a stored config with the character's default. */
export function resolveConfig(id: AmbientAssistantCharacter | undefined, config: MascotConfig | undefined): MascotConfig {
  const def = getMascot(id);
  return { ...def.defaults, ...(config || {}) };
}

// ---- React component ----------------------------------------------------
export interface MascotProps {
  character: AmbientAssistantCharacter;
  config?: MascotConfig;
  size?: number;
  waving?: boolean;
  className?: string;
  title?: string;
}

export function Mascot({ character, config, size = 64, waving, className = '', title }: MascotProps) {
  const def = getMascot(character);
  const cfg = resolveConfig(character, config);
  const { defs, inner } = def.build(cfg);
  const html = `<defs>${defs}</defs>${inner}`;
  return (
    <svg
      className={`aa-mascot aa-${character} ${className}${waving ? ' is-waving' : ''}`}
      viewBox="0 0 200 220"
      width={size}
      height={Math.round(size * 1.1)}
      role="img"
      aria-label={title || def.name}
      xmlns="http://www.w3.org/2000/svg"
      dangerouslySetInnerHTML={{ __html: html }}
    />
  );
}
