  const eyeOne = (x: number, y: number, r: number) => `<circle cx="${x}" cy="${y}" r="${r}" fill="#1a1f2b"/><circle cx="${x - r * 0.3}" cy="${y - r * 0.35}" r="${r * 0.34}" fill="#fff"/>`;
