/**
 * Ambient AI assistant mascots — a '90s software-buddy look (glossy volume,
 * specular highlights, chrome, cast shadows), built to be CUSTOMIZED rather
 * than picked from fixed presets. Each character exposes a set of slots
 * (face, glasses, hat, held item, colors…) with ~5 options each; the operator
 * clicks options in Settings → AI and the floating companion renders their
 * exact build.
 *
 * The SVG is assembled as a string (shared 3D toolkit below) and rendered via
 * an <svg> whose inner markup is injected — all generated by this module, no
 * user input, so the injection is safe. Animated parts carry `aa-part-*`
 * classes that the CSS in index.css drives (idle + a signature flourish while
 * the wrapper has `.is-waving`).
 */

// ---- 3D shading toolkit (string builders) -------------------------------
let gid = 0;
const uid = (p: string) => `${p}${gid++}`;

function sphere(light: string, base: string, dark: string) {
  const id = uid('sph');
  return {
    def: `<radialGradient id="${id}" cx="36%" cy="30%" r="72%"><stop offset="0%" stop-color="${light}"/><stop offset="45%" stop-color="${base}"/><stop offset="100%" stop-color="${dark}"/></radialGradient>`,
    fill: `url(#${id})`,
  };
}
function vgloss(top: string, bot: string) {
  const id = uid('vg');
  return { def: `<linearGradient id="${id}" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="${top}"/><stop offset="1" stop-color="${bot}"/></linearGradient>`, fill: `url(#${id})` };
}
function chrome() {
  const id = uid('cr');
  return { def: `<linearGradient id="${id}" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#f4f7fb"/><stop offset="0.25" stop-color="#9fb0c4"/><stop offset="0.5" stop-color="#e8eef5"/><stop offset="0.75" stop-color="#6b7c93"/><stop offset="1" stop-color="#c3cedd"/></linearGradient>`, fill: `url(#${id})` };
}
function shade(hex: string, amt: number) {
  const n = parseInt(hex.slice(1), 16);
  let r = (n >> 16) + amt, g = ((n >> 8) & 255) + amt, b = (n & 255) + amt;
  r = Math.max(0, Math.min(255, r)); g = Math.max(0, Math.min(255, g)); b = Math.max(0, Math.min(255, b));
  return '#' + ((1 << 24) + (r << 16) + (g << 8) + b).toString(16).slice(1);
}
function eye(cx: number, cy: number, r: number, look = 0, cls = '') {
  const s = sphere('#ffffff', '#f0f3f8', '#cfd7e2');
  const pr = r * 0.5;
  return { def: s.def, svg: `<g class="${cls}"><circle cx="${cx}" cy="${cy}" r="${r}" fill="${s.fill}" stroke="#c2ccd8" stroke-width="0.6"/><circle cx="${cx + look}" cy="${cy + r * 0.15}" r="${pr}" fill="#1a1f2b"/><circle cx="${cx + look - pr * 0.35}" cy="${cy + r * 0.15 - pr * 0.4}" r="${pr * 0.34}" fill="#fff"/></g>` };
}

interface Ctx { defs: string[]; blur: string; blur2: string; }
function newCtx(): Ctx {
  const blur = uid('sft'), blur2 = uid('sft');
  return {
    defs: [`<filter id="${blur}" x="-40%" y="-40%" width="180%" height="180%"><feGaussianBlur stdDeviation="2.4"/></filter><filter id="${blur2}" x="-60%" y="-60%" width="220%" height="220%"><feGaussianBlur stdDeviation="4.5"/></filter>`],
    blur, blur2,
  };
}
const castShadow = (c: Ctx, cx: number, cy: number, rx: number, ry: number) => `<ellipse cx="${cx}" cy="${cy}" rx="${rx}" ry="${ry}" fill="#000" opacity="0.30" filter="url(#${c.blur2})"/>`;
const spec = (c: Ctx, cx: number, cy: number, rx: number, ry: number, op = 0.85) => `<ellipse cx="${cx}" cy="${cy}" rx="${rx}" ry="${ry}" fill="#ffffff" opacity="${op}" filter="url(#${c.blur})"/>`;

